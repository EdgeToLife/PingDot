import Foundation

/// Все настройки в одном месте. Поменял — пересобери: ./build.sh install
enum Config {
    /// Кого пингуем. Цвет кружка считается по ЛУЧШЕМУ из узлов,
    /// так что один заглючивший сервер не испортит картину.
    static let hosts = ["8.8.8.8", "1.1.1.1"]

    /// Период опроса, секунд.
    static let interval: TimeInterval = 2
    /// Сколько ждать ответа на один пинг, секунд (должно быть меньше interval).
    static let timeout: TimeInterval = 1.5

    /// Сколько последних пингов на узел учитывать в статистике.
    /// 15 × 2 с ≈ последние 30 секунд.
    static let window = 15

    /// 🔴 — узел не ответил столько раз подряд.
    static let downAfter = 3

    /// 🟡 — у лучшего узла превышен хотя бы один порог
    /// (или потерян самый последний пинг).
    static let highLatencyMs = 150.0   // медиана пинга за окно
    static let highJitterMs  = 50.0    // средний скачок между соседними пингами
    static let highLoss      = 0.10    // доля потерь за окно: 0.10 = 10%, т.е. 2 из 15
}
